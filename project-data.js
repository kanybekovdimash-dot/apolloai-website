export function getProjectById(id) {
  return OPEN_PROJECTS.find((project) => project.id === id) || null;
}

export function getOpenRolesCount(project) {
  return project.roles.filter((role) => role.status === "open").length;
}

export function getProjectHref(id) {
  return `/project.html?id=${encodeURIComponent(id)}`;
}

export function getCountdownParts(targetDate) {
  const diff = new Date(targetDate).getTime() - Date.now();

  if (diff <= 0) {
    return null;
  }

  const totalMinutes = Math.floor(diff / 60000);
  const days = Math.floor(totalMinutes / (60 * 24));
  const hours = Math.floor((totalMinutes % (60 * 24)) / 60);
  const minutes = totalMinutes % 60;

  return { days, hours, minutes };
}

export function formatCountdown(targetDate) {
  const parts = getCountdownParts(targetDate);

  if (!parts) {
    return "Кастинг аяқталды";
  }

  return `${parts.days} күн ${parts.hours} сағ ${parts.minutes} мин`;
}


export async function loadProjects(apiBase = "") {
  const base = String(apiBase || "").replace(/\/$/, "");
  if (!base) {
    return OPEN_PROJECTS;
  }

  try {
    const response = await fetch(`${base}/projects-catalog`, {
      headers: {
        Accept: "application/json"
      }
    });

    const text = await response.text();
    const data = text ? JSON.parse(text) : {};
    if (!response.ok || data?.ok === false) {
      throw new Error(data?.error || "Projects catalog request failed");
    }

    const items = Array.isArray(data?.items) ? data.items.map(normalizeRemoteProject).filter(Boolean) : [];
    return items.length ? items : OPEN_PROJECTS;
  } catch {
    return OPEN_PROJECTS;
  }
}

export async function loadProjectById(id, apiBase = "") {
  const projects = await loadProjects(apiBase);
  return projects.find((project) => project.id === id) || projects[0] || OPEN_PROJECTS[0] || null;
}

function normalizeRemoteProject(project) {
  if (!project || typeof project !== "object") {
    return null;
  }

  return {
    id: String(project.id || "").trim() || crypto.randomUUID(),
    title: String(project.title || "").trim() || "Жоба",
    genre: String(project.genre || "").trim(),
    poster: String(project.poster || "").trim(),
    banner: String(project.banner || project.poster || "").trim(),
    promoVideoUrl: String(project.promoVideoUrl || project.promo_video_url || "").trim(),
    countdownDate: String(project.countdownDate || project.countdown_date || "").trim(),
    description: String(project.description || "").trim(),
    director: String(project.director || "").trim(),
    ageRange: String(project.ageRange || project.age_range || "").trim(),
    roles: Array.isArray(project.roles) ? project.roles.map(normalizeRemoteRole).filter(Boolean) : []
  };
}

function normalizeRemoteRole(role) {
  if (!role || typeof role !== "object") {
    return null;
  }

  return {
    id: String(role.id || "").trim() || crypto.randomUUID(),
    title: String(role.title || "").trim() || "Рөл",
    description: String(role.description || "").trim(),
    ageRange: String(role.ageRange || role.age_range || "").trim(),
    gender: String(role.gender || "").trim(),
    status: String(role.status || "open").trim() || "open",
    applicantsCount: Number(role.applicantsCount || role.applicants_count || 0) || 0,
    applicants: Array.isArray(role.applicants) ? role.applicants.map((item) => String(item || "").trim()).filter(Boolean) : [],
    selectedActor: role.selectedActor && typeof role.selectedActor === "object"
      ? {
          name: String(role.selectedActor.name || "").trim(),
          avatar: String(role.selectedActor.avatar || "").trim()
        }
      : null
  };
}
